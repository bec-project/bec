logger = bec_logger.logger

register_stop = threading.Event()


class DisabledDeviceError(Exception):
    """Exception raised when a disabled device is accessed"""


class InvalidDeviceError(Exception):
    """Exception raised when an invalid device is accessed"""


class ResponseState(str, enum.Enum):
    """Enum for the state of the response message"""

    COMPLETED = "completed"
    ERROR = "error"
    RUNNING = "running"


class RequestHandler:
    """
    Class to handle requests for device instructions. This class is responsible for storing device instructions and
    status objects and sending the appropriate responses back to redis.
    """

    def __init__(self, parent: DeviceServer):
        self.parent = parent
        self.connector = parent.connector
        self._storage = {}
        self._lock = threading.Lock()
        self._stopped_requests = deque(maxlen=50)

    def add_request(
        self,
        instr: messages.DeviceInstructionMessage,
        num_status_objects: int,
        done: bool = False,
        success: bool | None = None,
    ):
        """
        Add a new device instruction to the storage and the expected number of status objects.
        If the instruction is done, the success status must be set.

        Args:
            instr(messages.DeviceInstructionMessage): The instruction to add to the storage.
            num_status_objects(int): The number of status objects that are expected to be generated by the instruction.
            done(bool): Whether the instruction is done. Defaults to False.
            success(bool): Whether the instruction was successful. Defaults to None.
        """
        instr_id = instr.metadata["device_instr_id"]
        self._storage[instr_id] = {
            "instr": instr,
            "status_objects": [],
            "num_status_objects": num_status_objects,
            "done": done,
            "is_status_obj": None,
        }
        if done and success is None:
            raise ValueError("If the instruction is done, the success status must be set.")
        self.send_device_instruction_response(instr_id, success, done)

    def get_request(self, instr_id: str) -> dict | None:
        """
        Get a request from the storage.

        Args:
            instr_id(str): The ID of the instruction.
        """
        return self._storage.get(instr_id)

    def patch_num_status_objects(
        self, instr: messages.DeviceInstructionMessage, num_status_objects: int
    ) -> None:
        """
        Patch the number of status objects for a request.

        Args:
            instr(messages.DeviceInstructionMessage): The instruction to patch.
            num_status_objects(int): The new number of status objects.
        """
        instr_id = instr.metadata["device_instr_id"]
        request_info = self.get_request(instr_id)
        if request_info is None:
            return
        request_info["num_status_objects"] = num_status_objects

        self._update_instruction(instr_id)

    def remove_request(self, instr_id: str):
        """
        Remove a request from the storage.

        Args:
            instr_id(str): The ID of the instruction.
        """
        self._storage.pop(instr_id, None)

    def clear(self):
        """
        Clear the storage and remove all requests.
        """
        self._storage.clear()

    def add_status_object(self, instr_id: str, status_obj: OperationContext):
        """
        Add a status object to the storage.

        Args:
            instr_id(str): The ID of the instruction.
            status_obj(OperationContext): The status object to add.
        """
        if not isinstance(status_obj, OperationContext):
            status_obj = self.parent._context_for(status_obj)
        self._storage[instr_id]["status_objects"].append(status_obj)
        status_obj.add_callback(self.on_status_object_update)
        self._update_instruction(instr_id, is_status_obj=True)

    def set_finished(
        self,
        instr_id: str,
        success: bool = None,
        error_info: messages.ErrorInfo | None = None,
        result: Any = None,
    ):
        """
        Set the request to finished.

        Args:
            instr_id(str): The ID of the instruction.
            success(bool): Whether the instruction was successful. Defaults to None.
            error_info(messages.ErrorInfo, optional): Error information. Defaults to None.
            result(Any): The result of the instruction. Defaults to None. Only relevant for RPC calls.
        """
        with self._lock:
            request_info = self.get_request(instr_id)
            if request_info is None:
                return
            if success is None:
                if request_info["num_status_objects"] > 0:
                    success = all(
                        status_obj.success
                        for status_obj in self._storage[instr_id]["status_objects"]
                    )
                else:
                    success = True
            self.send_device_instruction_response(
                instr_id,
                success,
                done=True,
                error_info=error_info,
                result=result,
                is_status_obj=request_info["is_status_obj"],
            )
            self.remove_request(instr_id)

    def on_status_object_update(self, status_obj: OperationContext):
        """
        Callback for status updates from devices during device instructions.

        Args:
            status_obj(OperationContext): The status object that was updated.
        """
        instr_id = status_obj.instruction.metadata["device_instr_id"]
        with status_obj.callback_lock:
            if status_obj.processing or status_obj.processed:
                return
            status_obj.processing = True
        try:
            try:
                self.parent.status_callback(status_obj)
            except Exception as exc:
                logger.exception(f"Status callback failed for instruction {instr_id}")
                error = status_obj.exception() or exc
                status_obj.service_error = error
                error_info = self.get_error_info(error, status_obj)
                status_obj.service_error_info = error_info
                try:
                    self.parent.dispatch_status_response(
                        status_obj, status_obj.instruction.device, error_info=error_info
                    )
                except Exception:
                    logger.exception(
                        f"Error response publication failed for instruction {instr_id}"
                    )
                # A batch may still be registering peers when a terminal
                # completion invokes this observer inline. Preserve its expected
                # count and aggregate the service failure with all peer results.
                status_obj.processed = True
                self._update_instruction(instr_id, is_status_obj=True)
                return
            status_obj.processed = True
            self._update_instruction(instr_id, is_status_obj=True)
        finally:
            status_obj.service_done.set()

    def _update_instruction(self, instr_id: str, is_status_obj: bool = False) -> None:
        """
        Update the instruction in the storage.

        Args:
            instr_id(str): The ID of the instruction.
            is_status_obj(bool): Whether we are working with an ophyd status object as result.
        """
        request_info = self.get_request(instr_id)
        if request_info is None:
            return

        if not request_info["is_status_obj"] and is_status_obj:
            request_info["is_status_obj"] = True
            self.send_device_instruction_response(
                instr_id, success=False, done=False, is_status_obj=True, result=None
            )

        if len(request_info["status_objects"]) != request_info["num_status_objects"]:
            return

        status_objects = request_info["status_objects"]

        if all(status_obj.done and status_obj.processed for status_obj in status_objects):
            exceptions = [
                (status_obj.exception(), status_obj)
                for status_obj in status_objects
                if isinstance(status_obj, OperationContext)
            ]
            if any(val for val, _ in exceptions):
                error, obj = next((val, obj) for val, obj in exceptions if val)
                error_info = obj.service_error_info or self.get_error_info(error, obj)
                self.set_finished(instr_id, success=False, error_info=error_info)

            else:
                self.set_finished(instr_id, success=True)

    def get_error_info(self, error: Exception, obj: OperationContext) -> messages.ErrorInfo:
        """
        Get basic error information from an ophyd object.

        Args:
            error(Exception): The error that occurred.
            obj(StatusBase): The ophyd status object that caused the error.

        Returns:
            messages.ErrorInfo: A dictionary containing basic error information.
        """
        if isinstance(error, ExceptionWithErrorInfo):
            return error.error_info

        device_name = obj.target.identity.qualified_name

        msg = (
            f"{error.__class__.__name__}: {error}\n"
            f"The status {obj.__class__.__name__} from device {device_name} failed during the execution "
            f"of the following instruction:\n"
            f"{json_ext.dumps(obj.instruction, indent=2)}\n"
        )
        if obj.instruction.action:
            compact_msg = (
                f"An error occurred during '{obj.instruction.action}' on device '{device_name}'.\n\n"
                f"{error.__class__.__name__}: {str(error)}"
            )
        else:
            compact_msg = f"{error.__class__.__name__}: {str(error)}"
        error_info = messages.ErrorInfo(
            error_message=msg,
            compact_error_message=compact_msg,
            exception_type=error.__class__.__name__,
            device=device_name,
        )
        return error_info

    def send_device_instruction_response(
        self,
        instr_id: str,
        success: bool,
        done: bool,
        error_info: messages.ErrorInfo | None = None,
        result: Any = None,
        is_status_obj: bool | None = None,
    ):
        """
        Send a request status message.

        Args:
            instr_id(str): The ID of the instruction.
            success(bool): Whether the instruction was successful.
            done(bool): Whether the instruction is done.
            error_info(messages.ErrorInfo, optional): Error information. Defaults to None.
            result(Any): The result of the instruction. Defaults to None.
            is_status_obj(bool | None): Whether the result is a status object. Defaults to None.
        """
        metadata = self._storage[instr_id]["instr"].metadata
        stop_keys = ["RID", "scan_id", "queue_id"]
        if any(metadata.get(key) in self._stopped_requests for key in stop_keys):
            logger.info(
                f"Instruction with metadata {metadata} is in stopped requests, skipping response."
            )
            return

        if success:
            status = ResponseState.COMPLETED
        else:
            status = ResponseState.ERROR if done else ResponseState.RUNNING

        response_msg = messages.DeviceInstructionResponse(
            device=self._storage[instr_id]["instr"].content["device"],
            status=status.value,
            error_info=error_info,
            instruction_id=instr_id,
            instruction=self._storage[instr_id]["instr"],
            result=result,
            result_is_status=is_status_obj,
            metadata=metadata,
        )
        self.connector.send(MessageEndpoints.device_instructions_response(), response_msg)


class DeviceServer(BECService):
    """Coordinate device operations and publication through neutral handlers."""

    def __init__(
        self,
        config: str | ServiceConfig,
        connector_cls: type[RedisConnector],
        *,
        device_provider: DeviceProvider | None = None,
    ) -> None:
        """Initialize the device server.

        Args:
            config (str | ServiceConfig): Service configuration or its file path.
            connector_cls (type[RedisConnector]): Connector class used by the service.
        """
        self.device_provider = device_provider or create_device_provider()
        callback_monitor = self.device_provider.callback_monitor()
        super().__init__(config, connector_cls, unique_service=True)
        self.ophyd_callback_monitor = callback_monitor
        self._tasks = []
        self.connector.register(MessageEndpoints.stop_devices(), cb=self.on_stop_devices)
        self.executor = ThreadPoolExecutor(max_workers=4)
        self._start_device_manager()
        self.requests_handler = RequestHandler(self)
        self.rpc_handler = RPCHandler(self)

    def _start_device_manager(self):
        self.device_manager = DeviceManagerDS(self, status_cb=self.update_status)
        self.device_manager.initialize(self.bootstrap_server)

    def start(self) -> None:
        """start the device server"""
        if register_stop.is_set():
            register_stop.clear()

        self.connector.register(
            MessageEndpoints.device_instructions(),
            event=register_stop,
            cb=self.instructions_callback,
        )

        # Notify existing consumers before unblocking services waiting for startup.
        self.connector.send(
            MessageEndpoints.device_config_update(),
            messages.DeviceConfigMessage(action="reload", config={}),
        )
        self.status = BECStatus.RUNNING
        self.ophyd_callback_monitor.start()

    def update_status(self, status: BECStatus):
        """update the status of the device server"""
        self.status = status

    def stop(self) -> None:
        """stop the device server"""
        register_stop.set()
        self.status = BECStatus.IDLE

    def shutdown(self) -> None:
        """shutdown the device server"""
        self.ophyd_callback_monitor.request_stop()
        self.ophyd_callback_monitor.join(timeout=1)
        if not self.ophyd_callback_monitor.stopped:
            # A blocked diagnostics log sink must be interrupted before other
            # teardown code attempts to log through the same sink. Accepted
            # delivery failures remain observable through provider close.
            self.connector.shutdown()
        self.stop()
        errors = []
        try:
            # Drain accepted device events/completions while publication is still
            # available. The manager closes its connector after provider cleanup.
            if self.device_manager:
                try:
                    self.device_manager.shutdown()
                except Exception as error:
                    errors.append(error)
            try:
                self.device_provider.close()
            except Exception as error:
                errors.append(error)
        finally:
            try:
                # Also interrupts a diagnostics warning blocked in the Redis log sink.
                super().shutdown()
            finally:
                self.ophyd_callback_monitor.join()
                self.executor.shutdown(wait=True, cancel_futures=True)
        if errors:
            raise errors[0]

    def _update_device_metadata(self, instr) -> None:
        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]
        for dev in devices:
            device_root = dev.split(".")[0]
            self.device_manager.devices.get(device_root).metadata = instr.metadata

    def on_stop_devices(self, msg: MessageObject, **_kwargs) -> None:
        """
        Callback for receiving device stop requests.
        Handles stop-all (`None`), stop-none (`[]`), and stopping specific devices (device-name list).

        Args:
            msg: MessageObject containing the stop request.
        """
        mvalue: messages.VariableMessage = msg.value
        if mvalue is None:
            logger.warning("Failed to parse scan queue modification message.")
            return
        if mvalue.metadata.get("stop_id"):
            if isinstance(mvalue.metadata["stop_id"], str):
                self.requests_handler._stopped_requests.append(mvalue.metadata["stop_id"])
            elif isinstance(mvalue.metadata["stop_id"], list):
                # We don't allow None, so we remove it if present
                for stop_id in mvalue.metadata["stop_id"]:
                    if stop_id is not None:
                        self.requests_handler._stopped_requests.append(stop_id)
        if mvalue.value is None:
            self.stop_devices()
            logger.info("Received request to stop all devices.")
            return
        if mvalue.value == []:
            logger.info("Received request to stop no devices.")
            return
        logger.info(f"Received request to stop devices: {mvalue.value}")
        self.stop_devices(mvalue.value)

    def stop_devices(self, devices: list[str] | None = None) -> None:
        """
        Stop the specified devices or all devices if none are specified.

        Args:
            devices (list[str] | None): List of device names to stop. If None, all devices will be stopped.
        """
        self.status = BECStatus.BUSY
        if devices is None:
            logger.info("Stopping devices after receiving 'abort' request.")
            devices_to_stop = self.device_manager.devices.enabled_devices
        else:
            logger.info(f"Stopping devices {devices} after receiving 'abort' request.")
            devices_to_stop = [
                dev for dev in self.device_manager.devices.enabled_devices if dev.name in devices
            ]
        for dev in devices_to_stop:
            if dev.read_only:
                # don't stop devices that we haven't set
                continue
            if Capability.STOP in dev.handler.capabilities:
                try:
                    dev.handler.stop().result(timeout=10)
                except Exception as exc:  # pylint: disable=broad-except
                    content = traceback.format_exc()
                    error_info = messages.ErrorInfo(
                        error_message=content,
                        compact_error_message=traceback.format_exc(limit=0),
                        exception_type=exc.__class__.__name__,
                        device=dev.handler.identity.root,
                    )
                    self.connector.raise_alarm(
                        severity=Alarms.WARNING,
                        info=error_info,
                        metadata=self._get_metadata_for_alarm(None),
                    )
        self.status = BECStatus.RUNNING

    def assert_device_is_enabled(self, instructions: messages.DeviceInstructionMessage) -> None:
        """
        Assert that the device(s) in the instructions are enabled.

        Args:
            instructions (messages.DeviceInstructionMessage): The device instruction message.

        Raises:
            DisabledDeviceError: If any of the devices are disabled.
        """
        devices = instructions.content["device"]

        if isinstance(devices, str):
            devices = [devices]

        for dev in devices:
            dev = dev.split(".")[0]
            if not self.device_manager.devices[dev].enabled:
                raise DisabledDeviceError(f"Cannot access disabled device {dev}.")

    def assert_device_is_valid(self, instructions: messages.DeviceInstructionMessage) -> None:
        """
        Assert that the device(s) in the instructions are valid.

        Args:
            instructions (messages.DeviceInstructionMessage): The device instruction message.

        Raises:
            InvalidDeviceError: If any of the devices are invalid.
        """
        devices = instructions.content["device"]
        if not devices:
            raise InvalidDeviceError("At least one device must be specified.")
        if isinstance(devices, str):
            devices = [devices]
        for dev in devices:
            dev = dev.split(".")[0]
            if dev not in self.device_manager.devices:
                raise InvalidDeviceError(f"There is no device with the name {dev}.")

    def _get_metadata_for_alarm(
        self, instruction: messages.DeviceInstructionMessage | None = None
    ) -> dict:
        """
        Get the metadata for the current scan. This is used to add the scan ID and scan number to alarms.
        Returns:
            dict: Metadata dictionary with scan ID and scan number.
        """
        metadata = {}
        if instruction is not None:
            metadata.update(instruction.metadata)

        if not self.device_manager:
            return metadata

        if not self.device_manager.scan_info:
            return metadata

        msg = self.device_manager.scan_info.msg

        if not msg:
            return metadata

        scan_id_instruction = metadata.get("scan_id")
        if msg.scan_id == scan_id_instruction and msg.scan_number is not None:
            metadata["scan_number"] = msg.scan_number
        return metadata

    def _ensure_request_registered(
        self, instruction: messages.DeviceInstructionMessage | None
    ) -> None:
        """Register a placeholder request so early failures can still resolve."""
        if instruction is None:
            return
        instr_id = instruction.metadata.get("device_instr_id")
        if instr_id is None:
            return
        if self.requests_handler.get_request(instr_id) is None:
            self.requests_handler.add_request(instruction, num_status_objects=0)

    def handle_device_instructions(self, msg: messages.DeviceInstructionMessage) -> None:
        """Parse a device instruction message and handle the requested action. Action
        types are set, read, rpc, kickoff or trigger.

        Args:
            msg (str): A DeviceInstructionMessage string containing the action and its parameters

        """
        action = None
        instructions = msg
        try:
            action = instructions.content["action"]
            if action == "broadcast_scan_device_info" and not instructions.content["device"]:
                self._broadcast_scan_device_info(instructions)
                return
            if not instructions.content["device"]:
                return
            self.assert_device_is_valid(instructions)
            if action != "rpc":
                # rpc has its own error handling
                self.assert_device_is_enabled(instructions)
            self._update_device_metadata(instructions)

            if action == "set":
                self._set_device(instructions)
            elif action == "read":
                self._read_device(instructions)
            elif action == "rpc":
                self.rpc_handler.run_rpc(instructions)
            elif action == "kickoff":
                self._kickoff_device(instructions)
            elif action == "complete":
                self._complete_device(instructions)
            elif action == "trigger":
                self._trigger_device(instructions)
            elif action == "stage":
                self._stage_device(instructions)
            elif action == "unstage":
                self._unstage_device(instructions)
            elif action == "pre_scan":
                self._pre_scan(instructions)
            elif action == "broadcast_scan_device_info":
                self._broadcast_scan_device_info(instructions)
            else:
                logger.warning(f"Received unknown device instruction: {instructions}")
        except Exception as exc:  # pylint: disable=broad-except
            content = traceback.format_exc()
            if isinstance(exc, ExceptionWithErrorInfo):
                error_info = exc.error_info
                if not error_info.device:
                    error_info.device = self.device_provider.error_device(exc)
            else:
                compact_msg = traceback.format_exc(limit=0)
                error_info = messages.ErrorInfo(
                    error_message=content,
                    compact_error_message=compact_msg,
                    exception_type=exc.__class__.__name__,
                    device=self.device_provider.error_device(exc),
                )
            self._ensure_request_registered(instructions)
            if action == "rpc":
                self.rpc_handler.send_rpc_exception(exc, instructions)
            else:
                logger.error(content)

            if diid := instructions.metadata.get("device_instr_id"):
                self.requests_handler.set_finished(diid, success=False, error_info=error_info)

    @staticmethod
    def get_device_from_exception(exc: Exception) -> str | None:
        """Try to extract the device name from an exception message.

        Args:
            exc (Exception): The exception to extract the device name from.
        Returns:
            str | None: The device name if found, otherwise None.
        """
        return create_device_provider().error_device(exc)

    def instructions_callback(self, msg, **_kwargs) -> None:
        """callback for handling device instructions"""
        self.executor.submit(self.handle_device_instructions, msg.value)

    def _add_status_object_info(
        self,
        status: Completion[None],
        instruction: messages.DeviceInstructionMessage,
        device: DeviceHandler,
    ) -> OperationContext:
        """Associate request context without changing the native completion object."""
        context = OperationContext(status, instruction, device)
        return context

    def _context_for(self, value: object) -> OperationContext:
        if isinstance(value, OperationContext):
            return value
        text = "The status object has not received the metadata through the `_add_status_object_info` method properly."
        logger.error(text)
        raise ValueError(text)

    def _trigger_device(self, instr: messages.DeviceInstructionMessage) -> None:
        logger.trace(f"Trigger device: {instr}")
        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]
        devices = self.device_manager.get_device_order(devices)
        self.requests_handler.add_request(instr, num_status_objects=len(devices))
        for dev in devices:
            obj = self.device_manager.devices.get(dev)
            obj.metadata = instr.metadata
            obj = obj.handler
            status = obj.trigger()

            status = self._add_status_object_info(status, instr, obj)
            self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

    def _kickoff_device(self, instr: messages.DeviceInstructionMessage) -> None:
        logger.trace(f"Kickoff device: {instr}")

        obj = self.device_manager.devices.get(instr.content["device"]).handler
        kickoff_parameter = instr.content["parameter"].get("configure", {})
        status = obj.kickoff(kickoff_parameter, instr.metadata)
        if status is None:
            obj.flush_events(timeout=10)
            self.requests_handler.add_request(instr, num_status_objects=0, done=True, success=True)
            return
        self.requests_handler.add_request(instr, num_status_objects=1)

        status = self._add_status_object_info(status, instr, obj)
        self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

    def _complete_device(self, instr: messages.DeviceInstructionMessage) -> None:
        if instr.content["device"] is None:
            devices = [dev.name for dev in self.device_manager.devices.enabled_devices]
        else:
            devices = instr.content["device"]
            if not isinstance(devices, list):
                devices = [devices]

        devices = self.device_manager.get_device_order(devices)

        self.requests_handler.add_request(instr, num_status_objects=len(devices))
        num_status_objects = 0
        for dev in devices:
            obj = self.device_manager.devices.get(dev).handler
            if Capability.COMPLETE not in obj.capabilities:
                continue
            num_status_objects += 1
            logger.trace(f"Completing device: {dev}")
            status = obj.complete()
            if status is None:
                raise InvalidDeviceError(
                    f"The complete method of device {dev} does not return a StatusBase object."
                )

            status = self._add_status_object_info(status, instr, obj)
            self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

        self.requests_handler.patch_num_status_objects(instr, num_status_objects)

    def _set_device(self, instr: messages.DeviceInstructionMessage) -> None:
        self.requests_handler.add_request(instr, num_status_objects=1)
        device_name = instr.content["device"]
        child_access = None
        if "." in device_name:
            device_name, child_access = device_name.split(".", 1)
        device_obj = self.device_manager.devices.get(device_name)
        if device_obj.read_only:
            raise DisabledDeviceError(
                f"Setting the device {device_obj.name} is currently disabled."
            )
        logger.trace(f"Setting device: {instr}")
        val = instr.content["parameter"]["value"]
        obj = device_obj.handler.resolve(child_access or "")
        subscription = None
        if child_access:
            subscription = obj.subscribe_readback(self.device_manager._handle_device_event)
        try:
            status = obj.set(val)
        except Exception as exc:  # pylint: disable=broad-except
            exc = reformat_known_device_exceptions(
                exc, "set", f"Device: {device_name}, value: {val}."
            )
            status = Operation.failed(exc)
        status = self._add_status_object_info(status, instr, obj)
        status.subscription = subscription
        self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

    @staticmethod
    def convert_value_if_needed(obj: object, val: Any) -> Any:
        """
        Convert the value to the appropriate type if needed. This is particularly
        needed for ophyd signals that implement enum strings but are given as floats.

        Args:
            obj (ophyd.OphydObject): The ophyd object to set.
            val (Any): The value to set.

        Returns:
            Any: The converted value.
        """
        # Compatibility helper only; actual set/RPC normalization belongs to the provider.
        from bec_server.device_server.backend import legacy_convert_value

        return legacy_convert_value(obj, val)

    def _pre_scan(self, instr: messages.DeviceInstructionMessage) -> None:
        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]

        devices = self.device_manager.get_device_order(devices)

        self.requests_handler.add_request(instr, num_status_objects=len(devices))
        num_status_objects = 0
        for dev in devices:
            status = None
            obj = self.device_manager.devices[dev].handler
            if Capability.PRE_SCAN in obj.capabilities:
                status = obj.pre_scan()
            if status is None:
                obj.flush_events(timeout=10)
                continue
            if not isinstance(status, Completion):
                raise ValueError(
                    f"The pre_scan method of {dev} does not return a StatusBase object."
                )

            num_status_objects += 1
            status = self._add_status_object_info(status, instr, obj)
            self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

        self.requests_handler.patch_num_status_objects(instr, num_status_objects)

    @staticmethod
    def _close_operation_subscription(status: OperationContext) -> None:
        subscription, status.subscription = status.subscription, None
        if subscription is not None:
            subscription.close()

    def status_callback(self, status):
        status = self._context_for(status)
        pipe = self.connector.pipeline()
        obj = status.target
        try:
            obj.flush_events(timeout=10)
        except Exception as error:
            try:
                self._close_operation_subscription(status)
            except Exception as cleanup_error:
                error.add_note(f"Subscription disposal also failed: {cleanup_error!r}")
            raise
        self._close_operation_subscription(status)
        device_name = obj.identity.qualified_name
        if status.staging_state is not None:
            self._device_staged_callback(status)
        content = status.instruction.content
        is_config_set = content["action"] == "set"
        rpc_func = content["parameter"].get("func", "")
        is_rpc_set = content["action"] == "rpc" and (rpc_func == "set" or ".set" in rpc_func)

        if status.refresh:
            self.rpc_handler._update_cache(obj, status.instruction)
        if is_config_set or is_rpc_set:
            if obj.read_category == ReadCategory.CONFIGURATION:
                self._update_read_configuration(obj, status.instruction.metadata, pipe)
            elif obj.read_category == ReadCategory.NORMAL:
                # Refresh readback without replacing the request tracking this status.
                self._read_device(status.instruction, new_status=False)

        self.dispatch_status_response(status, device_name, pipe=pipe)
        pipe.execute()

    def dispatch_status_response(
        self,
        status: OperationContext,
        device_name: str,
        error_info: messages.ErrorInfo | None = None,
        pipe: Any = None,
    ) -> None:
        """Publish a requested client status response, including callback failures.

        Args:
            status (StatusBase): Completed status carrying the original instruction.
            device_name (str): Device name to include in the response.
            error_info (messages.ErrorInfo | None): Callback error overriding successful
                motion, if present. Otherwise, use the status exception. Defaults to None.
            pipe (Any): Optional pipeline used to queue the response. Defaults to None.

        Returns:
            None: The response is published or queued when requested.
        """
        instruction = status.instruction
        if not instruction.metadata.get("response"):
            return
        request_id = instruction.metadata["RID"]
        if error_info is None:
            error = status.exception()
            if error is not None:
                error_info = self.requests_handler.get_error_info(error, status)
        metadata = {"action": instruction.action, **instruction.metadata}
        metadata["error_info"] = error_info
        success = status.success if error_info is None else False
        dev_msg = messages.DeviceReqStatusMessage(
            device=device_name, success=success, request_id=request_id, metadata=metadata
        )
        logger.trace(f"req status for device {device_name}: {success}")
        self.connector.xadd(
            MessageEndpoints.device_req_status(request_id),
            {"data": dev_msg},
            pipe=pipe,
            expire=3600,
        )

    def _update_read_configuration(self, obj: DeviceHandler, metadata: dict, pipe) -> None:
        dev_config_msg = messages.DeviceMessage(
            signals=self.device_manager.devices[obj.identity.root].handler.read_configuration(),
            metadata=metadata,
        )
        self.connector.set_and_publish(
            MessageEndpoints.device_read_configuration(obj.identity.root), dev_config_msg, pipe
        )

    def _read_device(self, instr: messages.DeviceInstructionMessage, new_status=True) -> None:
        # check performance -- we might have to change it to a background thread
        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]

        devices = self.device_manager.get_device_order(devices)

        if not new_status:
            self._read_and_update_devices(devices, instr.metadata)
            return

        self.requests_handler.add_request(instr, num_status_objects=0)
        result = self._read_and_update_devices(devices, instr.metadata)
        response_result = result if instr.parameter.get("return_result", False) else None
        self.requests_handler.set_finished(
            instr.metadata["device_instr_id"], success=True, result=response_result
        )

    def _read_and_update_devices(self, devices: list[str], metadata: dict) -> list:
        start = time.time()
        pipe = self.connector.pipeline()
        signal_container = []
        devices = self.device_manager.get_device_order(devices)
        for dev in devices:
            device_root = dev.split(".")[0]
            self.device_manager.devices.get(device_root).metadata = metadata
            obj = self.device_manager.devices.get(device_root).handler
            try:
                signals = obj.read()
                signal_container.append(signals)
            # pylint: disable=broad-except
            except Exception as exc:
                signals = self._retry_obj_method(dev, obj, "read", exc)

            self.connector.set_and_publish(
                MessageEndpoints.device_read(device_root),
                messages.DeviceMessage(signals=signals, metadata=metadata),
                pipe,
            )
            self.connector.set_and_publish(
                MessageEndpoints.device_readback(device_root),
                messages.DeviceMessage(signals=signals, metadata=metadata),
                pipe,
            )
        pipe.execute()
        for dev in devices:
            self.device_manager.devices[dev.split(".")[0]].handler.flush_events(timeout=10)
        logger.trace(
            f"Elapsed time for reading and updating status info: {(time.time() - start) * 1000} ms"
        )
        return signal_container

    def _read_config_and_update_devices(self, devices: list[str], metadata: dict) -> list:
        start = time.time()
        pipe = self.connector.pipeline()
        signal_container = []
        devices = self.device_manager.get_device_order(devices)
        for dev in devices:
            self.device_manager.devices.get(dev).metadata = metadata
            obj = self.device_manager.devices.get(dev).handler
            try:
                signals = obj.read_configuration()
                signal_container.append(signals)
            # pylint: disable=broad-except
            except Exception as exc:
                signals = self._retry_obj_method(dev, obj, "read_configuration", exc)
            self.connector.set_and_publish(
                MessageEndpoints.device_read_configuration(dev),
                messages.DeviceMessage(signals=signals, metadata=metadata),
                pipe,
            )
        pipe.execute()
        for dev in devices:
            self.device_manager.devices[dev.split(".")[0]].handler.flush_events(timeout=10)
        logger.trace(
            f"Elapsed time for reading and updating status info: {(time.time() - start) * 1000} ms"
        )
        return signal_container

    def _retry_obj_method(
        self, device: str, obj: DeviceHandler, method: str, exc: Exception
    ) -> dict:
        error_info = messages.ErrorInfo(
            error_message=f"Failed to run {method} on device {device}.\n{traceback.format_exc()}",
            compact_error_message=traceback.format_exc(limit=0),
            exception_type=exc.__class__.__name__,
            device=device,
        )
        self.device_manager.connector.raise_alarm(
            severity=Alarms.WARNING, info=error_info, metadata=self._get_metadata_for_alarm()
        )
        device_root = device.split(".")[0]
        ds_dev = self.device_manager.devices.get(device_root)

        if ds_dev.on_failure == OnFailure.RETRY:
            # try to read it again, may have been only a glitch
            signals = getattr(obj, method)()
        elif ds_dev.on_failure == OnFailure.RAISE:
            raise exc
        elif ds_dev.on_failure == OnFailure.BUFFER:
            # if possible, fall back to past readings
            logger.warning(
                f"Failed to run {method} on device {device_root}. Trying to load an old value."
            )
            if method == "read":
                old_msg = self.connector.get(MessageEndpoints.device_read(device_root))
            elif method == "read_configuration":
                old_msg = self.connector.get(
                    MessageEndpoints.device_read_configuration(device_root)
                )
            else:
                raise ValueError(f"Unknown method {method}.")
            if not old_msg:
                raise exc
            signals = old_msg.content["signals"]
        else:
            raise ValueError(f"Unknown on_failure value {ds_dev.on_failure}.")
        return signals

    def _stage_device(
        self, instr: messages.DeviceInstructionMessage, timeout_on_unstage: int = 10
    ) -> None:
        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]

        devices = self.device_manager.get_device_order(devices)

        self.requests_handler.add_request(instr, num_status_objects=len(devices))

        num_status_objects = 0
        for dev in devices:
            status = None
            obj = self.device_manager.devices[dev].handler

            if not Capability.STAGE in obj.capabilities:
                continue

            # pylint: disable=protected-access
            if obj.staged:
                logger.info(
                    f"Device {obj.identity.root} was already staged and will be first unstaged."
                )
                status = self.device_manager.devices[dev].handler.unstage()
                if isinstance(status, Completion):
                    for ii in range(3):
                        try:
                            status.result(timeout=timeout_on_unstage)
                            status = None  # Set status None and break the loop since unstage is successful
                            break
                        except TimeoutError:
                            logger.warning(
                                f"Unstaging device {dev} still running, {timeout_on_unstage * (ii + 1)} seconds passed."
                            )
                    if status is not None:
                        raise ValueError(f"Unstaging device {dev} failed to finish in 30 seconds")
                obj.flush_events(timeout=10)
            status = self.device_manager.devices[dev].handler.stage()
            if status is None or isinstance(status, list):
                obj.flush_events(timeout=10)
                continue
            if not isinstance(status, Completion):
                raise ValueError(f"The stage method of {dev} does not return a StatusBase object.")
            num_status_objects += 1
            status = self._add_status_object_info(status, instr, obj)
            status.staging_state = 1
            self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

        self.requests_handler.patch_num_status_objects(instr, num_status_objects)

    def _device_staged_callback(self, status: OperationContext) -> None:
        """Set the device status to staged"""
        obj = status.target
        dev_name = obj.identity.root
        instr = status.instruction
        state = status.staging_state
        self.connector.set(
            MessageEndpoints.device_staged(dev_name),
            messages.DeviceStatusMessage(device=dev_name, status=state, metadata=instr.metadata),
        )
        if state == 1:  # Device was/is staged
            obj = self.device_manager.devices[dev_name].handler
            # pylint: disable=protected-access
            if Capability.STAGE in obj.capabilities and not obj.staged:
                raise ValueError(f"Failed to stage device {dev_name}.")

    def _unstage_device(self, instr: messages.DeviceInstructionMessage) -> None:
        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]

        devices = self.device_manager.get_device_order(devices)

        self.requests_handler.add_request(instr, num_status_objects=len(devices))
        num_status_objects = 0
        for dev in devices:
            status = None
            obj = self.device_manager.devices[dev].handler
            if Capability.STAGE in obj.capabilities:
                # pylint: disable=protected-access
                if obj.staged:
                    status = self.device_manager.devices[dev].handler.unstage()
                else:
                    logger.debug(f"Device {obj.identity.root} was already unstaged.")
            if status is None or isinstance(status, list):
                obj.flush_events(timeout=10)
                continue
            if not isinstance(status, Completion):
                raise ValueError(
                    f"The unstage method of {dev} does not return a StatusBase object."
                )
            num_status_objects += 1
            status = self._add_status_object_info(status, instr, obj)
            status.staging_state = 0
            self.requests_handler.add_status_object(instr.metadata["device_instr_id"], status)

        self.requests_handler.patch_num_status_objects(instr, num_status_objects)

    def _broadcast_scan_device_info(self, instr: messages.DeviceInstructionMessage) -> None:
        """
        Broadcast a snapshot of device runtime information for the scan.

        Args:
            instr (messages.DeviceInstructionMessage): The request containing the devices
                and scan ID.
        """
        instr_id = instr.metadata["device_instr_id"]
        self.requests_handler.add_request(instr, num_status_objects=0)

        devices = instr.content["device"]
        if not isinstance(devices, list):
            devices = [devices]

        device_info: dict[str, messages.DeviceRuntimeInfo] = {}
        scan_id = instr.parameter.get("scan_id")
        if scan_id is None:
            self.requests_handler.set_finished(instr_id, success=True)
            return

        for dev in devices:
            if dev not in self.device_manager.devices:
                logger.warning(f"Device {dev} not found in device manager. Skipping.")
                continue
            obj = self.device_manager.devices.get(dev).handler

            signal_info = obj.runtime_info()

            if not signal_info:
                continue
            device_info[dev] = messages.DeviceRuntimeInfo(signal_info=signal_info)

        self.connector.xadd(
            MessageEndpoints.scan_device_info(),
            {
                "data": messages.ScanDeviceInfoMessage(
                    devices=device_info, scan_id=scan_id, metadata=instr.metadata
                )
            },
            max_size=10,
        )
        self.requests_handler.set_finished(instr_id, success=True)
